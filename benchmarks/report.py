def _plt():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({
        "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "axes.edgecolor": GRID, "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2,
        "text.color": INK, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8,
        "axes.axisbelow": True, "axes.spines.top": False, "axes.spines.right": False,
        "font.size": 10, "legend.frameon": False,
    })
    return plt


def grouped_bars(path: str, title: str, groups: List[str], series: Dict[str, List[float]], ylabel: str, subtitle: str):
    plt = _plt()
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150)
    n = len(series)
    width = 0.8 / max(n, 1)
    xs = list(range(len(groups)))
    for i, (label, vals) in enumerate(series.items()):
        pos = [x - 0.4 + width * (i + 0.5) for x in xs]
        ax.bar(pos, [v if v == v else 0 for v in vals], width=width * 0.9, color=SERIES[i], label=label,
               edgecolor=SURFACE, linewidth=1.5)
        for p_, v in zip(pos, vals):  # selective direct labels: values on top of each bar
            if v == v:
                ax.text(p_, v, fmt(v, 2 if v < 10 else 0), ha="center", va="bottom", fontsize=7, color=INK2)
    ax.set_xticks(xs, groups)
    ax.grid(axis="x", visible=False)
    ax.set_ylabel(ylabel)
    ax.set_title(title, loc="left", fontsize=11, color=INK)
    fig.text(0.01, 0.01, subtitle, fontsize=7, color=INK2)
    if n >= 2:
        ax.legend(loc="upper left", ncol=n)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(path)
    plt.close(fig)


def lines(path: str, title: str, x: List[int], series: Dict[str, List[float]], xlabel: str, ylabel: str, subtitle: str):
    plt = _plt()
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150)
    for i, (label, vals) in enumerate(series.items()):
        ax.plot(x, vals, color=SERIES[i], linewidth=2, marker="o", markersize=5, label=label)
        if vals:
            ax.annotate(label, (x[-1], vals[-1]), xytext=(6, 0), textcoords="offset points", fontsize=8, color=INK2, va="center")
    ax.set_xticks(x)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_title(title, loc="left", fontsize=11, color=INK)
    fig.text(0.01, 0.01, subtitle, fontsize=7, color=INK2)
    if len(series) >= 2:
        ax.legend(loc="upper left")
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(path)
    plt.close(fig)


