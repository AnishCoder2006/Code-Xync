def sec_b2() -> List[str]:
    docs = loads("b2-queue-c*-n*.json")
    out: List[str] = []
    if docs:
        out += ["| WORKER_CONCURRENCY | Submitted | Accepted (timed) | 429 | 503 | enqueue→container p50 ms | p95 ms | p99 ms | p95 spread | queue-wait p95 ms | BullMQ final states |",
                "|---|---|---|---|---|---|---|---|---|---|---|"]
        key = lambda d: (d["conditions"]["worker_concurrency"], d["conditions"]["concurrent_submissions"])  # noqa: E731
        series: Dict[str, Dict[int, float]] = {}
        for d in sorted(docs, key=key):
            c, m, ex = d["conditions"], med(d), median_run(d).get("extra", {})
            out.append(f"| {c['worker_concurrency']} | {c['concurrent_submissions']} | {ex.get('jobs_with_timing')} | {ex.get('http_429')} | {ex.get('http_503')} | "
                       f"{fmt(m.get('p50'))} | {fmt(m.get('p95'))} | {fmt(m.get('p99'))} | {spread(d, 'p95')} | {fmt(ex.get('queue_wait_ms', {}).get('stats', {}).get('p95'))} | "
                       f"{json.dumps(ex.get('bullmq_job_states', {}))} |")
            series.setdefault(f"concurrency {c['worker_concurrency']}", {})[c["concurrent_submissions"]] = m.get("p95", float("nan"))
        xs = sorted({n for s in series.values() for n in s})
        lines(os.path.join(CHARTS, "b2-queue-p95.png"), "Enqueue → container start, p95 (median of 3 runs)", xs,
              {k: [v.get(x, float("nan")) for x in xs] for k, v in sorted(series.items(), key=lambda kv: int(kv[0].split()[-1]))},
              "concurrent submissions", "milliseconds",
              "Accepted jobs only (503s excluded, counted in the table). Docker Desktop on Windows. Source: benchmarks/results/b2-queue-*.json")
        cap = docs[0]["conditions"].get("max_queue_length")
        big = [d for d in docs if d["conditions"]["concurrent_submissions"] > (cap or 10**9)]
        if big:
            measured = [r for d in big for r in d["runs"] if not r.get("warmup")]
            acc = [r["extra"].get("jobs_with_timing", 0) for r in measured]
            rej = sum(r["extra"].get("http_503", 0) for r in measured)
            subm = sum(r["extra"].get("submitted", 0) for r in measured)
            out += ["", f"**Back-pressure not enforced under concurrent submissions:** with MAX_QUEUE_LENGTH={cap}, the {len(measured)} measured "
                        f"100-submission batches accepted {min(acc)}–{max(acc)} jobs each; only {rej} of {subm} submissions got 503. "
                        "The API reads the queue length and enqueues in separate steps, so simultaneous requests all see a short queue."]
        c0 = docs[0]["conditions"]
        out += ["", "![B2 queue delay](benchmarks/results/charts/b2-queue-p95.png)", "",
                f"Conditions: {c0['submission']}; program `{c0['program']}`; MAX_QUEUE_LENGTH={c0['max_queue_length']} (503 = queue full); {c0['rate_limit']}; {c0['docker']}."]
    cold = loads("b2-coldstart-*.json")
    if cold:
        out += ["", "| Sandbox cold start | p50 ms | p95 ms | p99 ms | p95 spread | docker run spawn→exit p50 ms | Conditions |", "|---|---|---|---|---|---|---|"]
        for d in cold:
            m, ex, c = med(d), median_run(d).get("extra", {}), d["conditions"]
            out.append(f"| {c['language']} (`{c['image']}`) | {fmt(m.get('p50'))} | {fmt(m.get('p95'))} | {fmt(m.get('p99'))} | {spread(d, 'p95')} | "
                       f"{fmt(ex.get('docker_run_spawn_to_exit_ms', {}).get('stats', {}).get('p50'))} | {c['samples_ms_is']}; {c['jobs']}; {c['docker']} |")
    return out or ["_No B2 results yet._"]


