"""
Build the Phase 6 report from benchmarks/results/*.json ONLY.

    python benchmarks/report.py                 # writes benchmarks/results/REPORT.md + charts/*.png
    python benchmarks/report.py --update-readme # also replaces the Results block in README.md

Every number printed here is read from a results file; nothing is typed in by hand.
Each table row carries its conditions. Missing inputs are reported as missing.
Charts: matplotlib, light theme, palette slots 1-3 of the validated reference palette
(at most three series per chart; legend always present for >= 2 series).
"""
