# Reference palette, light mode (validated set: slots 1-3 pass all-pairs CVD checks).
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]


def load(name: str) -> Optional[Dict[str, Any]]:
    p = os.path.join(RES, f"{name}.json")
    if not os.path.isfile(p):
        return None
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def loads(pattern: str) -> List[Dict[str, Any]]:
    out = []
    for p in sorted(glob.glob(os.path.join(RES, pattern))):
        with open(p, encoding="utf-8") as f:
            out.append(json.load(f))
    return out


def fmt(x: Any, nd: int = 1) -> str:
    if x is None:
        return "null"
    if isinstance(x, float):
        if x != x:  # NaN
            return "n/a"
        return f"{x:.{nd}f}"
    return str(x)


def med(doc: Dict[str, Any]) -> Dict[str, Any]:
    return (doc.get("summary") or {}).get("median_stats") or {}


def spread(doc: Dict[str, Any], k: str) -> str:
    s = ((doc.get("summary") or {}).get("spread") or {}).get(k)
    return f"{fmt(s['min'])}–{fmt(s['max'])}" if s else "n/a"


def median_run(doc: Dict[str, Any]) -> Dict[str, Any]:
    mr = (doc.get("summary") or {}).get("median_run")
    for r in doc.get("runs", []):
        if r.get("run") == mr and not r.get("warmup"):
            return r
    return {}


def provenance(doc: Dict[str, Any]) -> str:
    g, e = doc.get("git", {}), doc.get("environment", {})
    commit = g.get("commit") or f"no commit (uncommitted tree, source digest {g.get('source_digest')})"
    return f"{doc.get('timestamp')} · {commit} · {e.get('os')} · {e.get('cpu')} x{e.get('logical_cpus')} · {e.get('ram_gib')} GiB · Docker {e.get('docker')}"


